const LanguageContext = createContext(null);

export function t(text) {
  if (typeof text !== "string")
    return text;
  try {
    return localStorage.getItem(STORAGE_KEY) === "te" ? (te[text] ?? text) : text;
  } catch {
    return text;
  }
}

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    try {
      return localStorage.getItem(STORAGE_KEY) === "te" ? "te" : "en";
    } catch {
      return "en";
    }
  });
  const setPreferredLanguage = (next) => {
    const value = next === "te" ? "te" : "en";
    try {
      localStorage.setItem(STORAGE_KEY, value);
    } catch {
      // The preference still applies for this page if storage is unavailable.
    }
    setLanguage(value);
  };
  const value = useMemo(() => ({ language, setLanguage: setPreferredLanguage }), [language]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context)
    throw new Error("useLanguage must be used inside LanguageProvider");
  return context;
}
